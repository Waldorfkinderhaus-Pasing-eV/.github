#!/usr/bin/env python3
"""Check commit messages and pull request texts against the commit policy (ADR-0014, architecture shared/README.md)."""
import argparse
import json
import os
import re
import subprocess
import sys
import unicodedata
import urllib.error
import urllib.request
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import baseline  # noqa: E402

GITHUB_TIMEOUT_SECONDS = 120
PAGE_SIZE = 100  # GitHub's largest page
MAX_SUBJECT_TAIL = 95  # after the first character: a title of about 100 characters

TYPES = ('feat', 'fix', 'docs', 'test', 'refactor', 'perf', 'build', 'ci', 'chore', 'revert')
TITLE = re.compile(rf'^({"|".join(TYPES)})(\([a-z0-9]+(?:-[a-z0-9]+)*\))?!?: \S.{{0,{MAX_SUBJECT_TAIL}}}$')
REVERT = re.compile(r'^(?:Revert|Reapply) "(.+)"$')  # git revert / the GitHub button; the inner title is checked
LOCAL_ONLY = re.compile(r'^(fixup|squash|amend)! ')  # rewritten before they can be pushed
SCISSORS = re.compile(r'^# -+ >8 -+$', re.M)  # `git commit -v` appends the diff below this line
EDITOR_COMMENT = re.compile(r'^#( |$)')  # git's own template lines, never a deliberate '#word'

# Whole trailer value (name part) of a known assistant. Anchored so human names do not match.
AGENT_NAME = re.compile(
    r'^(claude(\s+(code|(opus|sonnet|haiku|fable)\b.*|\d.*))?|(github\s+)?copilot\b.*|codex\b.*|chatgpt\b.*|'
    r'gpt-?\d.*|openai\b.*|anthropic|gemini(\s+(cli|code\s+assist))?|google\s+jules|jules|cursor(\s+agent)?|'
    r'aider\b.*|devin(\.ai)?|openhands|amp|sourcegraph\s+amp|cody|windsurf|cascade|qwen\b.*|deepseek\b.*|kiro)$',
    re.I)
AGENT_EMAIL = re.compile(r'\[bot\]|^noreply@(anthropic|openai)\.com$', re.I)
# Wording such as "Generated with Claude Code": the verb must be followed by the preposition
# and the product, so "generated by hand" or "created with openai-style keys" are fine.
PHRASE = re.compile(
    r'\b(generated|created|written|made|built|drafted|authored|assisted|produced|co-?authored)\s+'
    r'(with|by|using|via)\s+(the\s+)?\[?(claude[-\s]?(code)?|chatgpt|(github\s+)?copilot|codex|gemini|openai|anthropic|'
    r'an?\s+ai\b|ai\s+(assistan\w+|tools?|agents?))'
    r'(\]\([^)]*\))?\s*[.!]?\s*$', re.I | re.M)  # the product must end the line, as in footers
FOOTER = re.compile(r'claude\.ai/code|claude\.com/claude-code|\N{ROBOT FACE}', re.I)
BY_LINE = re.compile(r'^\s*([A-Za-z][A-Za-z-]*-by)\s*:\s*(.*)$', re.I | re.M)  # anywhere, not only git's trailer block
TRAILER = re.compile(r'^([A-Za-z][A-Za-z-]*):\s*(.*)$')
IDENTITY = re.compile(r'^(.*?)\s*<([^<>]*)>\s*$')


def normalize(text):
    """Fold compatibility forms (fullwidth colon) and drop invisible format characters."""
    text = unicodedata.normalize('NFKC', text)
    return ''.join(c for c in text if unicodedata.category(c) != 'Cf')


def parse_trailers(text):
    """Trailers exactly as git defines them (the last paragraph), as (key, value) pairs."""
    result = subprocess.run(['git', 'interpret-trailers', '--parse'], input=text, capture_output=True,
                            text=True, encoding='utf-8', check=True)
    return [m.groups() for m in map(TRAILER.match, result.stdout.splitlines()) if m]


def agent_identity(name, email=''):
    return bool(AGENT_NAME.match(name.strip()) or AGENT_EMAIL.search(name) or AGENT_EMAIL.search(email))


def check_attribution(text):
    text = normalize(text)
    problems = []
    for key, value in BY_LINE.findall(text):
        match = IDENTITY.match(value)
        name, email = match.groups() if match else (value, '')
        name = re.sub(r'\([^)]*\)|["\']', '', name).strip()  # decorations: "Claude" or Claude (Sonnet 4.5)
        if agent_identity(name, email):
            problems.append(f'{key} names an AI agent or bot ({name or email})')
    if PHRASE.search(text) or FOOTER.search(text):
        problems.append('AI attribution wording or footer ("Generated with ...")')
    if problems:
        problems.append('AI attribution is forbidden; the human author owns the commit')
    return problems


def check_title(title):
    while inner := REVERT.match(title):  # Revert "Revert "..."" and Reapply "..." nest
        title = inner.group(1)
    if not TITLE.match(title):
        return [f'title must be "<type>(<scope>): <subject>" with type in {", ".join(TYPES)}: {title!r}']
    return []


def check_message(message, author_email=None, hook=False):
    if hook:
        message = SCISSORS.split(message)[0]
        message = '\n'.join(line for line in message.splitlines() if not EDITOR_COMMENT.match(line))
    text = message.strip()
    if not text:
        return ['empty commit message']
    problems = check_attribution(text)
    title = text.splitlines()[0]
    if hook and (LOCAL_ONLY.match(title) or title.startswith('Merge ')):
        return problems  # title and sign-off are checked once the commit is rewritten or pushed
    problems += check_title(title)
    signoffs = [m.group(2).lower() for key, value in parse_trailers(normalize(text))
                if key.lower() == 'signed-off-by' and (m := IDENTITY.match(value))]
    if not signoffs:
        problems.append('missing "Signed-off-by:" trailer (use git commit -s)')
    elif author_email and author_email.lower() not in signoffs:
        problems.append('the Signed-off-by e-mail must equal the commit author\'s e-mail '
                        '(git commit -s signs off as the committer; use the same identity for both)')
    return problems


def git(*args):
    return subprocess.run(['git', *args], check=True, capture_output=True, text=True, encoding='utf-8').stdout


def check_range(revision_range):
    problems = {}
    records = git('log', '--no-merges', '--format=%H%x1f%an%x1f%ae%x1f%B%x1e', revision_range).split('\x1e')
    for record in filter(str.strip, records):
        sha, name, email, message = record.strip('\n').split('\x1f', 3)
        found = check_message(message, author_email=email)
        if agent_identity(name, email):
            found.append('author identity is an agent or bot; commits must be authored by the responsible human')
        if found:
            problems[sha[:12]] = found
    return problems


class NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        return None  # the token must never follow a redirect to another host


def github_api(path):
    """GET one GitHub REST resource. Needs GH_TOKEN or GITHUB_TOKEN; never put the token in Git."""
    token = os.environ.get('GH_TOKEN') or os.environ.get('GITHUB_TOKEN')
    if not token:
        raise RuntimeError('Set GH_TOKEN to check signatures (the Commit policy workflow provides it).')
    request = urllib.request.Request('https://api.github.com' + path, headers={
        'Authorization': 'Bearer ' + token, 'Accept': 'application/vnd.github+json',
        'X-GitHub-Api-Version': '2022-11-28', 'User-Agent': 'WKP-commit-policy'})
    try:
        with urllib.request.build_opener(NoRedirect()).open(request, timeout=GITHUB_TIMEOUT_SECONDS) as response:
            return json.loads(response.read())
    except urllib.error.HTTPError as error:
        raise RuntimeError(f'GitHub API returned HTTP {error.code}; check the token and repository.') from None


def check_verified(number):
    # In Actions the running repository wins, so a rename or fork does not target the old one.
    repo = os.environ.get('GITHUB_REPOSITORY') or baseline.configuration(baseline.repository_root(), 'commits').get(
        'repository', '')
    if not re.fullmatch(r'[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+', repo):
        raise SystemExit('Name the repository as owner/name in shared/config.json, "commits": {"repository": ...}')
    problems, page = {}, 1
    while True:
        commits = github_api(f'/repos/{repo}/pulls/{number}/commits?per_page={PAGE_SIZE}&page={page}')
        for item in commits:
            if len(item.get('parents', [])) > 1:
                continue  # merge commits are created by GitHub or checked through their parents
            verification = item.get('commit', {}).get('verification', {})
            if verification.get('verified') is not True:
                problems[item['sha'][:12]] = [f'signature not verified by GitHub ({verification.get("reason", "unknown")}); '
                                              'sign with git commit -S and upload the public key to GitHub']
        if len(commits) < PAGE_SIZE:
            return problems
        page += 1


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--message-file')
    parser.add_argument('--range')
    parser.add_argument('--title')
    parser.add_argument('--body')
    parser.add_argument('--verified-pr')
    args = parser.parse_args(argv)
    if all(value is None for value in vars(args).values()):
        parser.error('choose at least one check')
    problems = {}
    if args.message_file:
        with open(args.message_file, encoding='utf-8') as stream:
            message = stream.read()
        try:
            ident = git('var', 'GIT_AUTHOR_IDENT')
        except subprocess.CalledProcessError:
            print('Set your Git identity first: git config user.name / user.email', file=sys.stderr)
            return 1
        email = re.search(r'<([^<>]*)>', ident)
        found = check_message(message, author_email=email.group(1) if email else None, hook=True)
        if found:
            problems['commit message'] = found
    if args.title is not None:
        found = check_title(args.title) + check_attribution(args.title)
        if found:
            problems['pull request title'] = found
    if args.body:
        found = check_attribution(args.body)
        if found:
            problems['pull request description'] = found
    if args.range:
        problems.update(check_range(args.range))
    if args.verified_pr:
        for sha, found in check_verified(args.verified_pr).items():
            problems.setdefault(sha, []).extend(found)
    for where, found in problems.items():
        for problem in found:
            print(f'{where}: {problem}', file=sys.stderr)
    if problems:
        print('See CONTRIBUTING.md and the architecture contribution standard for the commit rules.', file=sys.stderr)
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
